# 简称后面紧跟这些字，多半是在说某个**具体地点**而不是行政区：
# 「去白云山」「逛海珠广场」都不是在说白云区/海珠区
_PLACE_SUFFIXES = frozenset("山湖塔寺街路园馆城港站岛桥苑村江海湾口门场楼观宫庙岭南厦幢号")

# 简称后面是这些字（或到句尾），才认为他在说"要去这个区"：去南沙玩 / 南沙一日游 / 南沙，吃海鲜
_AREA_TAILS = frozenset("玩逛吃住游转行旅的来了去在，。！？、；：  " "附近周日月年一两三四五六七八九十")


# 抠出来的区名里出现这些虚词/代词，说明拿到的是句子片段（「这个地区」）而不是行政区名
_AREA_CORE_STOP_CHARS = frozenset(
    "这那个些某是的了着和与或把被在有无很太就都也还才只要会可能去到住游逛玩想我你他她它"
)


# ===== 区级天气：坐标表 =====
# 为什么需要它：广州南北跨度 100+ 公里，南沙和从化同一天能差 3~5℃。
# 只按"广州市中心"一个点取天气，等于让全城用户看同一个数字，
# 而"我在南沙，为什么给我看越秀的天气"是最容易被一眼看穿的错误。
#
# 覆盖策略：给本系统的主场城市（广州）配齐 11 个区的区中心坐标；
# 其余城市暂按市中心——宁可显示"广州市中心"，也不假造一个区级精度。
