def canonical_district(name: str) -> str | None:
    """区名归一化成字典里的写法（「南沙」→「南沙区」）；未收录返回 None。"""
    if not name:
        return None
    if name in DISTRICT_TO_CITY:
        return name
    core = area_core(name)
    if len(core) < 2:
        return None
    for full in DISTRICT_TO_CITY:
        if area_core(full) == core:
            return full
    return None


def district_coords(name: str) -> tuple[float, float] | None:
    """区名 → (纬度, 经度)。简称（「南沙」）与全称（「南沙区」）都认；未收录返回 None。"""
    if not name:
        return None
    if name in DISTRICT_COORDS:
        return DISTRICT_COORDS[name]
    core = area_core(name)
    for full, coords in DISTRICT_COORDS.items():
        if area_core(full) == core:
            return coords
    return None


def districts_of_city(city: str) -> list[str]:
    """某城市在字典里收录的区名（带后缀），按名称排序。"""
    return sorted(name for name, owners in DISTRICT_TO_CITY.items() if city in owners)


def area_core(name: str) -> str:
    """去掉行政区后缀：「南沙区」→「南沙」、「东涌镇」→「东涌」。"""
    for suffix in AREA_SUFFIXES:
        if name.endswith(suffix) and len(name) > len(suffix):
            return name[: -len(suffix)]
    return name


def cities_of(name: str) -> tuple[str, ...]:
    """区名 → 所属城市；未知返回空元组。"""
    if name in DISTRICT_TO_CITY:
        return DISTRICT_TO_CITY[name]
    core = area_core(name)
    if len(core) < 2:
        return ()
    for full, owners in DISTRICT_TO_CITY.items():
        if area_core(full) == core:
            return owners
    return ()


def match_area(text: str) -> tuple[str, str] | None:
    """从需求里解析市辖区，返回 (规范区名, 命中的原词)；认不出返回 None。

    三级匹配，从严到宽：
    1. 全称：「南沙区」「浦东新区」——最明确
    2. 已知区名的简称：「去南沙玩」——后面必须跟"要出行"的字
       （否则「白云山」「海珠广场」会被误判成白云区、海珠区）
    3. 通用「XX区/县/镇」——覆盖字典里没收录的区

    之所以不一上来就用正则：`\\w+区` 会从「去南沙区」里抠出「去南沙区」，
    也会把「这个地区」当成行政区。先查字典能避开绝大多数误判。
    """
    raw = (text or "").strip()
    if not raw:
        return None

    # 1. 全称（多个命中取最长的，避免被短名截胡）
    hits = [(index, name) for name in DISTRICT_TO_CITY if (index := raw.find(name)) >= 0]
    if hits:
        hits.sort(key=lambda item: (item[0], -len(item[1])))
        best = max(hits, key=lambda item: len(item[1]))
        return best[1], best[1]

    # 2. 简称
    weak: list[tuple[int, str, str]] = []
    for name in DISTRICT_TO_CITY:
        core = area_core(name)
        index = raw.find(core)
        if index < 0:
            continue
        tail = raw[index + len(core) : index + len(core) + 1]
        if tail and tail not in _AREA_TAILS:
            continue  # 后面还跟着别的字（白云山/天河城），不是在说区
        weak.append((index, core, name))
    if weak:
        weak.sort(key=lambda item: (item[0], -len(item[1])))
        return weak[0][2], weak[0][1]

    # 3. 通用规则（字典未收录的区）
    pattern = re.compile(r"(?:去|到|在|住|游|逛|玩|的|了|想)?([\u4e00-\u9fa5]{2,3})(新区|开发区|区|县|镇)")
    for matched in pattern.finditer(raw):
        core, suffix = matched.group(1), matched.group(2)
        full = f"{core}{suffix}"
        if full in _AREA_STOPWORDS or core in _AREA_STOPWORDS:
            continue
        if set(core) & _AREA_CORE_STOP_CHARS:
            continue  # 「这个地区」这类句子片段，不是行政区名
        return full, full
    return None
